Windows 手工验收（请使用新建测试工作区及空白记事本）
1. 启动网页和桌面，确认同一会话、任务、授权和产物。
2. 扩展与自动化 → 桌面控制 → 启用桌面输入。
3. 创建真实模型任务，勾选 desktop.action；通过 windows 找到记事本 hwnd。
4. 将记事本切到前台，observe 获取控件及 observation；批准向编辑控件输入测试内容。
5. 确认输入后重新 observe；切到其他窗口再输入，应拒绝并停止。
6. Ctrl+Alt+F12 / 页面紧急停止后，所有后续输入应被拒绝。
7. 暂停任务、人工接管，再启用时必须重新观察。
8. 使用中文/空格路径，测试多屏、DPI 改变、窗口移动/关闭后的拒绝行为。
9. 不保存测试记事本内容，关闭测试窗口。不要操作真实用户文档。
10. Unity/Office 验证独立记录；未安装或未实测时不标记通过。
